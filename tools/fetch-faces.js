// Builds the famous-faces picture bank from Wikipedia lead images that carry a free licence
// (CC BY, CC BY-SA, CC0 or public domain), with attribution kept for each photo.
// Writes web/faces/<id>.jpg and web/content-faces.js. Run: node tools/fetch-faces.js
const fs = require('fs'); const path = require('path'); const { execFileSync } = require('child_process');
const list = JSON.parse(fs.readFileSync(path.resolve(__dirname, 'faces-list.json'), 'utf8'));
const UA = { 'User-Agent': 'ZingQuiz/1.0 (family quiz app; contact via github.com/jondoesflow/Family-Game)', 'Accept': 'application/json' };
const sleep = ms => new Promise(r => setTimeout(r, ms));
const outDir = path.resolve(__dirname, '..', 'web/faces'); fs.mkdirSync(outDir, { recursive: true });
const strip = s => String(s || '').replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();

(async () => {
  const faces = [], skipped = [];
  for (let i = 0; i < list.length; i++) {
    const [name, level] = list[i];
    try {
      const getJSON = async (u) => { for (let a = 0; a < 4; a++) { const r = await fetch(u, { headers: UA }); const t = await r.text(); try { return JSON.parse(t); } catch (e) { await sleep(8000 * (a + 1)); } } throw new Error('rate limited'); };
      const sum = await getJSON('https://en.wikipedia.org/api/rest_v1/page/summary/' + encodeURIComponent(name.replace(/ /g, '_')));
      const src = sum.originalimage && sum.originalimage.source;
      if (!src || !/\/wikipedia\/commons\//.test(src)) { skipped.push(name + ': no free lead image'); continue; }
      const file = decodeURIComponent(src.split('?')[0].split('/').pop());
      const api = `https://commons.wikimedia.org/w/api.php?action=query&titles=${encodeURIComponent('File:' + file)}&prop=imageinfo&iiprop=extmetadata|url&iiurlwidth=640&format=json`;
      const info = await getJSON(api);
      const pages = info.query && info.query.pages; const page = pages && pages[Object.keys(pages)[0]];
      const ii = page && page.imageinfo && page.imageinfo[0];
      if (!ii) { skipped.push(name + ': no image info'); continue; }
      const meta = ii.extmetadata || {};
      const licence = strip(meta.LicenseShortName && meta.LicenseShortName.value);
      if (!/^(CC BY(-SA)?( \d\.\d)?|CC0|Public domain|PDM|OGL)/i.test(licence) || /NC|ND/i.test(licence)) { skipped.push(`${name}: licence "${licence}"`); continue; }
      const artist = strip(meta.Artist && meta.Artist.value).slice(0, 80) || 'Unknown';
      const thumb = ii.thumburl || ii.url;
      const buf = Buffer.from(await (await fetch(thumb, { headers: { 'User-Agent': UA['User-Agent'] } })).arrayBuffer());
      const id = 'f' + (faces.length + 1);
      const raw = path.join(outDir, id + '.raw');
      fs.writeFileSync(raw, buf);
      // Square crop biased to the top (faces sit high in portraits), resize to 420px, JPEG.
      execFileSync('python3', ['-c', `
from PIL import Image, ImageOps
im = Image.open(${JSON.stringify(raw)}); im = ImageOps.exif_transpose(im).convert('RGB')
w, h = im.size; s = min(w, h)
left = (w - s) // 2; top = 0 if h > w else 0
if h > w: top = int((h - s) * 0.12)
im = im.crop((left, top, left + s, top + s)).resize((420, 420), Image.LANCZOS)
im.save(${JSON.stringify(path.join(outDir, id + '.jpg'))}, 'JPEG', quality=82, optimize=True)
`]);
      fs.unlinkSync(raw);
      faces.push({ id, name, level, img: 'faces/' + id + '.jpg', credit: { artist, licence, file: 'https://commons.wikimedia.org/wiki/File:' + encodeURIComponent(file) } });
      if (faces.length % 10 === 0) console.log(`faces ${faces.length} (${i + 1}/${list.length})`);
    } catch (e) { skipped.push(name + ': ' + e.message); }
    await sleep(2500);
  }
  const js = `/* Famous faces: Wikipedia/Wikimedia Commons lead images under free licences, with attribution.\n   Generated by tools/fetch-faces.js. Images live in web/faces/. */\nwindow.CONTENT_FACES = {\nfaces: [\n${faces.map(f => JSON.stringify(f)).join(',\n')}\n]\n};\n`;
  fs.writeFileSync(path.resolve(__dirname, '..', 'web/content-faces.js'), js);
  console.log(`wrote web/content-faces.js: ${faces.length} faces`);
  if (skipped.length) { console.log('skipped:'); skipped.forEach(s => console.log(' - ' + s)); }
})();
