// Pulls the whole verified question set from the Open Trivia Database (opentdb.com,
// licensed CC BY-SA 4.0) and writes web/content-trivia.js.
// Run: node tools/import-opentdb.js   (takes ~10 minutes: the API allows one request every 5 seconds)
const fs = require('fs'); const path = require('path');

const EXCLUDE = new Set([24, 26, 31]);          // Politics, Celebrities, Anime & Manga
const CAPS = { 15: 220, 29: 150, 32: 220 };      // Video Games, Comics, Cartoons: stop them dominating
const LEVEL = { easy: 2, medium: 3, hard: 4 };   // 2 Family, 3 Grown-up, 4 Expert
const MAX_Q_WORDS = 30, MAX_OPT_WORDS = 9;
// Facts that drift with time, and living political figures, are left out.
const STALE = /\b(as of|currently|so far|to date|most recent(ly)?|latest|newest|this year|right now|most[- ]visited|most popular|highest[- ]grossing|best[- ]selling|richest|oldest living|world record|record holder)\b/i;
const POLITICS = /\b(Trump|Obama|Biden|Clinton|Putin|Brexit|Boris Johnson|Nigel Farage)\b/i;
const FROM_RAW = process.argv.includes('--from-raw');

const sleep = ms => new Promise(r => setTimeout(r, ms));
const dec = s => Buffer.from(s, 'base64').toString('utf8');
async function getJSON(url) { const r = await fetch(url); return r.json(); }

function tidyCat(name) {
  return name.replace(/^Entertainment: /, '').replace(/^Science: /, '').replace('Musicals & Theatres', 'Theatre').replace('Cartoon & Animations', 'Cartoons').replace('Japanese Anime & Manga', 'Anime');
}
function tidyText(s) {
  return s.replace(/\s+/g, ' ').replace(/&quot;/g, '"').replace(/&#039;/g, "'").replace(/&amp;/g, '&').replace(/&rsquo;/g, '’').replace(/&ldquo;|&rdquo;/g, '"').replace(/&eacute;/g, 'é').trim();
}

(async () => {
  const cats = (await getJSON('https://opentdb.com/api_category.php')).trivia_categories;
  const rawPath = path.resolve(__dirname, '..', 'dist-opentdb-raw.json');
  const raw = FROM_RAW ? JSON.parse(fs.readFileSync(rawPath, 'utf8')) : [];
  const tok = FROM_RAW ? null : (await getJSON('https://opentdb.com/api_token.php?command=request')).token;
  let amount = 50, empties = 0;
  for (let i = 0; i < 400 && !FROM_RAW; i++) {
    await sleep(5200);
    let d;
    try { d = await getJSON(`https://opentdb.com/api.php?amount=${amount}&encode=base64&token=${tok}`); } catch (e) { console.log('network error, retrying'); continue; }
    if (d.response_code === 5) { console.log('rate limited, waiting'); await sleep(6000); continue; }
    if (d.response_code === 4) { console.log('token exhausted: all questions fetched'); break; }
    if (d.response_code === 1) { if (amount === 50) { amount = 10; continue; } if (amount === 10) { amount = 1; continue; } if (++empties > 3) break; continue; }
    if (d.response_code !== 0) { console.log('response', d.response_code); continue; }
    raw.push(...d.results);
    if ((i + 1) % 10 === 0) console.log(`fetched ${raw.length}`);
  }
  console.log('raw total', raw.length);
  if (!FROM_RAW) fs.writeFileSync(rawPath, JSON.stringify(raw));

  // Skip anything that duplicates a hand-written question.
  global.window = {};
  require(path.resolve(__dirname, '..', 'web/content-core.js'));
  require(path.resolve(__dirname, '..', 'web/content-extra.js'));
  const seen = new Set();
  [...window.CONTENT.quiz, ...window.CONTENT_EXTRA.quiz, ...window.CONTENT_EXTRA.tf].forEach(x => seen.add(x.q.trim().toLowerCase()));
  const quiz = [], tf = [], perCat = {};
  let n = 0;
  for (const r of raw) {
    const catRaw = dec(r.category); const catId = cats.find(c => c.name === catRaw)?.id;
    if (EXCLUDE.has(catId)) continue;
    perCat[catId] = (perCat[catId] || 0) + 1;
    if (CAPS[catId] && perCat[catId] > CAPS[catId]) continue;
    const q = tidyText(dec(r.question));
    if (q.split(' ').length > MAX_Q_WORDS) continue;
    if (STALE.test(q) || POLITICS.test(q)) continue;
    const key = q.toLowerCase(); if (seen.has(key)) continue; seen.add(key);
    const level = LEVEL[dec(r.difficulty)];
    const cat = tidyCat(catRaw);
    const id = 'o' + (++n);
    if (dec(r.type) === 'boolean') {
      tf.push({ id, level, cat, q, answer: dec(r.correct_answer) === 'True' });
    } else {
      const correct = tidyText(dec(r.correct_answer));
      const wrong = r.incorrect_answers.map(x => tidyText(dec(x)));
      const options = [correct, ...wrong];
      if (options.length !== 4) continue;
      if (options.some(o => o.split(' ').length > MAX_OPT_WORDS || !o)) continue;
      if (new Set(options.map(o => o.toLowerCase())).size !== 4) continue;
      quiz.push({ id, level, cat, q, options, answer: 0 });
    }
  }
  const out = `/* Questions from the Open Trivia Database (https://opentdb.com), licensed CC BY-SA 4.0.\n   Generated by tools/import-opentdb.js. Levels: 2 Family (easy), 3 Grown-up (medium), 4 Expert (hard). */\nwindow.CONTENT_TRIVIA = {\nquiz: [\n${quiz.map(x => JSON.stringify(x)).join(',\n')}\n],\ntf: [\n${tf.map(x => JSON.stringify(x)).join(',\n')}\n]\n};\n`;
  fs.writeFileSync(path.resolve(__dirname, '..', 'web/content-trivia.js'), out);
  const byLevel = [2, 3, 4].map(l => [...quiz, ...tf].filter(x => x.level === l).length);
  console.log(`wrote web/content-trivia.js: ${quiz.length} multiple choice, ${tf.length} true/false | family ${byLevel[0]}, grown-up ${byLevel[1]}, expert ${byLevel[2]}`);
})();
